"""Domain models for modular security attacks and multi-turn execution traces."""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from arbiter_securitybench.adapters.models import (
    ConversationMessage,
    ModelInformation,
    RateLimitConfig,
    RetryPolicyConfig,
    TokenUsage,
)
from arbiter_securitybench.contracts import SecurityCategory


class AttackCategory(StrEnum):
    """Supported adversarial attack categories for the attack execution engine."""

    PROMPT_INJECTION = "prompt_injection"
    JAILBREAK = "jailbreak"
    SYSTEM_PROMPT_EXTRACTION = "system_prompt_extraction"
    SENSITIVE_DATA_LEAKAGE = "sensitive_data_leakage"
    INSTRUCTION_HIERARCHY_MANIPULATION = "instruction_hierarchy_manipulation"

    def to_security_category(self) -> SecurityCategory:
        """Map an attack category to the corresponding benchmark SecurityCategory."""
        mapping = {
            AttackCategory.PROMPT_INJECTION: SecurityCategory.PROMPT_INJECTION,
            AttackCategory.JAILBREAK: SecurityCategory.JAILBREAK_RESISTANCE,
            AttackCategory.SYSTEM_PROMPT_EXTRACTION: SecurityCategory.SYSTEM_PROMPT_EXTRACTION,
            AttackCategory.SENSITIVE_DATA_LEAKAGE: SecurityCategory.SENSITIVE_DATA_LEAKAGE,
            AttackCategory.INSTRUCTION_HIERARCHY_MANIPULATION: SecurityCategory.PROMPT_INJECTION,
        }
        return mapping[self]


class AttackVariant(BaseModel):
    """Deterministic adversarial prompt sequence generated by an Attack."""

    model_config = ConfigDict(frozen=True)

    variant_id: str = Field(min_length=1, max_length=128)
    attack_id: str = Field(min_length=1, max_length=128)
    turns: list[str] = Field(min_length=1)
    system_context: str | None = None
    initial_history: list[ConversationMessage] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)

    @property
    def is_multi_turn(self) -> bool:
        return len(self.turns) > 1


class AttackTurnRecord(BaseModel):
    """Recorded single turn inside a single-turn or multi-turn attack execution."""

    model_config = ConfigDict(frozen=True)

    turn_index: int = Field(ge=0)
    prompt: str = Field(min_length=1)
    response_text: str
    latency_seconds: float = Field(ge=0.0)
    token_usage: TokenUsage | None = None
    model_information: ModelInformation | None = None
    raw_response: dict[str, Any] = Field(default_factory=dict)
    execution_metadata: dict[str, Any] = Field(default_factory=dict)


class AttackExecutionOutput(BaseModel):
    """Normalized output collected from executing an attack against a target."""

    model_config = ConfigDict(frozen=True)

    attack_id: str
    category: AttackCategory
    variant_id: str
    turns: list[AttackTurnRecord] = Field(min_length=1)
    final_response_text: str
    total_latency_seconds: float = Field(ge=0.0)
    conversation_history: list[ConversationMessage] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)


class AttackExecutionConfig(BaseModel):
    """Runtime execution constraints for AttackExecutionEngine."""

    model_config = ConfigDict(frozen=True)

    per_turn_timeout_seconds: float = Field(default=30.0, gt=0.0)
    per_test_timeout_seconds: float = Field(default=120.0, gt=0.0)
    retry_policy: RetryPolicyConfig = Field(
        default_factory=lambda: RetryPolicyConfig(max_retries=0)
    )
    rate_limit: RateLimitConfig | None = None
    seed: int = Field(default=0, ge=0)
    execute_variants: bool = Field(default=False)
    max_variants_per_test: int = Field(default=1, ge=1, le=10)
    allowed_target_ids: frozenset[str] | None = None
    disconnect_on_finish: bool = Field(default=False)
